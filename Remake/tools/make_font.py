"""Build src/font_cp437.h: a 256-glyph 8x8 CP437 font for the PAC-GAL remake.
Remake using Claude Opus 5.5, Nov 2026
Guided by Brett Hallen


Glyph data comes from Daniel Hepper's public-domain font8x8
(https://github.com/dhepper/font8x8, itself from Marcel Sondaar's public-domain
IBM VGA-derived font).  CP437 characters that font8x8 lacks (smileys, card
suits, a few symbols) are drawn here by hand.
Usage: python3 make_font.py <font8x8 dir> > ../src/font_cp437.h
"""
import re, sys, os

def load(path):
    txt = open(path).read()
    rows = re.findall(r'\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}\s*,\s*//\s*U\+([0-9A-Fa-f]{4})', txt)
    return {int(u, 16): [int(b, 16) for b in r.split(',')] for r, u in rows}

d = sys.argv[1]
uni = {}
for f in ('font8x8_basic.h', 'font8x8_ext_latin.h', 'font8x8_box.h', 'font8x8_block.h', 'font8x8_greek.h', 'font8x8_misc.h'):
    uni.update(load(os.path.join(d, f)))

def art(rows):  # 8 strings of 8 chars, '#' = pixel; LSB = leftmost
    out = []
    for r in rows:
        v = 0
        for i, ch in enumerate(r):
            if ch == '#': v |= 1 << i
        out.append(v)
    return out

HAND = {
    0x01: art([" ###### ", "#      #", "# #  # #", "#      #", "# #### #", "#  ##  #", "#      #", " ###### "]),  # ☺
    0x02: art([" ###### ", "########", "## ## ##", "########", "##    ##", "###  ###", "########", " ###### "]),  # ☻
    0x03: art([" ## ##  ", "####### ", "####### ", "####### ", " #####  ", "  ###   ", "   #    ", "        "]),  # ♥
    0x04: art(["   #    ", "  ###   ", " #####  ", "####### ", " #####  ", "  ###   ", "   #    ", "        "]),  # ♦
    0x05: art(["  ###   ", " #####  ", "  ###   ", "####### ", "####### ", "  # #   ", "  ###   ", "        "]),  # ♣
    0x06: art(["   #    ", "  ###   ", " #####  ", "####### ", "####### ", "  ###   ", "  ###   ", "        "]),  # ♠
    0x07: art(["        ", "        ", "   ##   ", "  ####  ", "  ####  ", "   ##   ", "        ", "        "]),  # •
    0xF9: art(["        ", "        ", "        ", "   ##   ", "   ##   ", "        ", "        ", "        "]),  # ∙
    0xFA: art(["        ", "        ", "        ", "        ", "   #    ", "        ", "        ", "        "]),  # ·
    0xFE: art(["        ", "        ", "  ####  ", "  ####  ", "  ####  ", "  ####  ", "        ", "        "]),  # ■
}

glyphs, missing = [], []
for code in range(256):
    if code in HAND:
        glyphs.append(HAND[code]); continue
    u = ord(bytes([code]).decode('cp437')) if code >= 32 else None
    if code == 0 or code == 32:
        glyphs.append([0] * 8)
    elif u is not None and u in uni:
        glyphs.append(uni[u])
    else:
        glyphs.append([0] * 8); missing.append(code)

print('/* font_cp437.h - CP437 8x8 font for the PAC-GAL (Al J. Jimenez, May 1982) remake.')
print(' * Remake using Claude Opus 5.5, Nov 2026')
print(' * Guided by Brett Hallen')
print(' * Generated by tools/make_font.py; glyphs public domain (see that file).')
print(' */')
print('#ifndef FONT_CP437_H\n#define FONT_CP437_H\n')
print('static const unsigned char font_cp437[256][8] = {')
for code, g in enumerate(glyphs):
    print('    {' + ','.join(f'0x{b:02X}' for b in g) + f'}}, /* 0x{code:02X} */')
print('};\n')
print(f'/* blank (not used by PAC-GAL): {" ".join(f"{c:02X}" for c in missing)} */')
print('#endif')
