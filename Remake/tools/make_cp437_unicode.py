"""Build src/cp437_unicode.h: CP437 code -> UTF-8 text, for the terminal version.
Remake using Claude Opus 5.5, Nov 2026
Guided by Brett Hallen

Codes 0x01-0x1F and 0x7F are the IBM PC's graphic symbols (smileys, card
suits...), not control characters.  Usage: python3 make_cp437_unicode.py > ../src/cp437_unicode.h
"""
LOW = " ☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"
print('/* cp437_unicode.h - CP437 to UTF-8 for the PAC-GAL (Al J. Jimenez, May 1982) remake.')
print(' * Remake using Claude Opus 5.5, Nov 2026')
print(' * Guided by Brett Hallen')
print(' * Generated by tools/make_cp437_unicode.py.')
print(' */')
print('#ifndef CP437_UNICODE_H\n#define CP437_UNICODE_H\n')
print('static const char *const cp437_utf8[256] = {')
for code in range(256):
    if code < 32: ch = LOW[code]
    elif code == 0x7F: ch = '⌂'
    else: ch = bytes([code]).decode('cp437')
    if code == 0xFF: ch = ' '                      # non-breaking space -> plain space
    esc = ''.join(f'\\x{b:02X}' for b in ch.encode('utf-8')) if (ord(ch) > 127 or ch in '"\\') else ch
    print(f'    "{esc}",' + (f' /* 0x{code:02X} */' if code % 8 == 0 else ''))
print('};\n\n#endif')
